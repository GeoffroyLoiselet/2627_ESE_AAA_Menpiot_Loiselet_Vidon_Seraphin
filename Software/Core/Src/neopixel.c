/*
 * WS2812 / NeoPixel driver for STM32G431 (Inverter_STM32G431CBU6.ioc)
 *
 *  Pin  : PB4  (PWM_NEO) = TIM3_CH1
 *  Timer: TIM3, 160 MHz / (PSC+1 = 10) = 16 MHz, ARR = 19 -> 20 ticks = 1.25 us (800 kHz)
 *  DMA  : DMA1_Channel1, memory -> TIM3 CCR1, half-word, normal mode
 *
 *  Bit "0": CCR = 6  (0.375 us high)
 *  Bit "1": CCR = 13 (0.8125 us high)
 *  Reset  : trailing slots with CCR = 0 (line low > 50 us)
 */
#include "neopixel.h"

extern TIM_HandleTypeDef htim3;          /* generated by CubeMX in main.c */

#define NEO_T0           6
#define NEO_T1           13
#define NEO_RESET_SLOTS  60              /* 60 * 1.25 us = 75 us */
#define NEO_BUF_LEN      (NEO_NUM_LEDS * 24 + NEO_RESET_SLOTS)

static uint8_t           pixels[NEO_NUM_LEDS][3];   /* stored as G, R, B */
static uint16_t          dmaBuf[NEO_BUF_LEN];
static volatile uint8_t  busy = 0;

void Neo_SetPixel(uint16_t idx, uint8_t r, uint8_t g, uint8_t b)
{
    if (idx >= NEO_NUM_LEDS) return;
    pixels[idx][0] = g;
    pixels[idx][1] = r;
    pixels[idx][2] = b;
}

void Neo_SetAll(uint8_t r, uint8_t g, uint8_t b)
{
    for (uint16_t i = 0; i < NEO_NUM_LEDS; i++) Neo_SetPixel(i, r, g, b);
}

/* pos 0..767 -> smooth RGB colour wheel, scaled by brightness (0..255) */
void Neo_Wheel(uint16_t pos, uint8_t brightness, uint8_t *r, uint8_t *g, uint8_t *b)
{
    pos %= 768;
    uint8_t seg = pos >> 8;
    uint8_t x   = pos & 0xFF;
    uint8_t rr, gg, bb;

    switch (seg) {
        case 0:  rr = 255 - x; gg = x;       bb = 0;       break;
        case 1:  rr = 0;       gg = 255 - x; bb = x;       break;
        default: rr = x;       gg = 0;       bb = 255 - x; break;
    }
    *r = (rr * brightness) >> 8;
    *g = (gg * brightness) >> 8;
    *b = (bb * brightness) >> 8;
}

HAL_StatusTypeDef Neo_Show(void)
{
    if (busy) return HAL_BUSY;

    uint32_t n = 0;
    for (uint16_t i = 0; i < NEO_NUM_LEDS; i++) {
        for (uint8_t c = 0; c < 3; c++) {
            uint8_t v = pixels[i][c];
            for (int8_t bit = 7; bit >= 0; bit--) {
                dmaBuf[n++] = (v & (1u << bit)) ? NEO_T1 : NEO_T0;
            }
        }
    }
    while (n < NEO_BUF_LEN) dmaBuf[n++] = 0;      /* reset / latch */

    busy = 1;
    HAL_StatusTypeDef st = HAL_TIM_PWM_Start_DMA(&htim3, TIM_CHANNEL_1,
                                                 (uint32_t *)dmaBuf, NEO_BUF_LEN);
    if (st != HAL_OK) busy = 0;
    return st;
}

uint8_t Neo_IsBusy(void) { return busy; }

void Neo_Init(void)
{
    /* TIM3 + DMA are already set up by MX_TIM3_Init() / MX_DMA_Init() */
    Neo_SetAll(0, 0, 0);
    Neo_Show();
    while (busy) { }
}

/* Called by HAL when the last DMA word has been written to CCR1 */
void HAL_TIM_PWM_PulseFinishedCallback(TIM_HandleTypeDef *htim)
{
    if (htim->Instance == TIM3) {
        HAL_TIM_PWM_Stop_DMA(htim, TIM_CHANNEL_1);
        busy = 0;
    }
}
